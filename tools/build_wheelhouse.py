"""Prepare offline wheelhouses and hash locks on the release machine (never on a client).

pip evaluates environment markers against the running interpreter, so platform-specific
requirements (for example colorama on Windows) are resolved explicitly per target.
"""

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    "windows-x64": (["win_amd64"], "win32"),
    "macos-arm64": (["macosx_11_0_arm64", "macosx_14_0_arm64"], "darwin"),
    "macos-x86_64": (["macosx_10_9_x86_64", "macosx_10_13_x86_64", "macosx_11_0_x86_64"], "darwin"),
}


def requirements(platform: str) -> list[str]:
    result = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        requirement, _, marker = line.partition(";")
        match = re.search(r'sys_platform\s*==\s*"([a-z0-9]+)"', marker)
        if marker.strip() and (not match or match[1] != platform):
            continue
        result.append(requirement.strip())
    return result


def build(output: Path) -> None:
    for target, (platforms, sys_platform) in TARGETS.items():
        wheels = output / "wheelhouse" / target
        wheels.mkdir(parents=True, exist_ok=False)
        pinned = requirements(sys_platform)
        command = [
            sys.executable,
            "-m",
            "pip",
            "download",
            "--only-binary=:all:",
            "--no-deps",
            "--python-version",
            "3.12",
            "--implementation",
            "cp",
            "--dest",
            str(wheels),
        ]
        for platform in platforms:
            command += ["--platform", platform]
        subprocess.run([*command, *pinned], check=True)
        lock = output / "locks" / f"{target}.txt"
        lock.parent.mkdir(parents=True, exist_ok=True)
        lines = [f"# Offline lock for {target}; generated by tools/build_wheelhouse.py"]
        names = {re.split(r"[=<>]", p)[0].lower().replace("_", "-"): p for p in pinned}
        for wheel in sorted(wheels.glob("*.whl")):
            project = wheel.name.split("-")[0].lower().replace("_", "-")
            digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
            lines.append(f"{names.pop(project)} --hash=sha256:{digest}")
        if names:
            raise SystemExit(f"Missing wheels for {target}: {sorted(names)}")
        lock.write_text("\n".join(lines) + "\n")
        print(f"{target}: {len(lines) - 1} wheels")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    build(parser.parse_args().output.resolve())


if __name__ == "__main__":
    main()
